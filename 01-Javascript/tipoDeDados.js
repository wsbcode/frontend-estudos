// TIPOS DE DADOS

// 1. Number (Número)
// Serve para qualquer tipo de número, seja inteiro ou com casas decimais (separadas por ponto).
let idade = 33;

// 2. String (Texto)
// Serve para textos. Você sempre deve colocar o texto entre aspas (simples, duplas ou crases).
let nome = "William";

// 3. Boolean (Booleano)

// É um tipo de dado que só aceita dois valores: ou é verdadeiro (true) ou é falso (false). É muito usado para tomadas de decisão no código

// Verdadeiro
let oUsuarioEstaLogado = true;

// Falso
let temChovendoHoje = false;

// 4. Undefined (Indefinido)

// Acontece quando você cria uma variável, mas não coloca nenhum valor dentro dela ainda. O JavaScript automaticamente diz que o valor dela é "indefinido".
let meuResultado;

// 5. Null (Nulo)

// Serve para quando você quer, de propósito, deixar uma variável totalmente vazia. É diferente do undefined, porque aqui você escolheu deixar sem nada.
// Informando que a variável está vazia de propósito
let cargoAtual = null;

// 6. Array (Lista)

// Serve para guardar uma lista de informações organizadas. Imagine uma caixa com várias divisórias. Usamos os colchetes [ ] para criar um Array.
let listaDeCompras = ["Arroz", "Feijão", "Café"];

// Criando uma lista de números
let numerosDaSorte = [7, 14, 21, 33];

// 7. Object (Objeto)

// Serve para representar algo do mundo real, guardando informações detalhadas através de propriedades e valores (como uma ficha cadastral). Usamos as chaves { } para criar um Objeto.
let usuario = {
   nome: "William",
   idade: 33,
   estaAtivo: true,
};
